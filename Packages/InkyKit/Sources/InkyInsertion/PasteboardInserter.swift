import AppKit
import ApplicationServices
import Carbon.HIToolbox
import InkyCore
import os

/// Insère du texte en passant par le presse-papier :
///
/// 1. on sauvegarde le contenu actuel du presse-papier (texte, image, fichiers…) ;
/// 2. on y met le texte dicté ;
/// 3. on simule ⌘V dans l'app au premier plan ;
/// 4. on attend un court instant que l'app ait lu le presse-papier ;
/// 5. on remet le contenu d'origine (si personne ne l'a changé entre-temps).
///
/// C'est la méthode la plus universelle (elle marche dans quasiment toutes les
/// apps), au prix de ce petit aller-retour sur le presse-papier.
@MainActor
public final class PasteboardInserter: TextInserter {
    /// Remettre l'ancien contenu après le collage.
    public var restoreClipboard = true
    /// Délai avant restauration. Trop court : certaines apps lentes collent
    /// l'ANCIEN contenu. Trop long : rien de grave, juste plus lent à revenir.
    public var restoreDelay: Duration = .milliseconds(350)

    private let pasteboard: NSPasteboard
    private let logger = Logger(subsystem: "com.byteonedev.inky", category: "insertion")

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    public func insert(_ text: String) async throws(InsertionError) {
        // Champ mot de passe actif (ou « saisie sécurisée » de Terminal) : macOS
        // ignorerait notre ⌘V. On laisse le texte dans le presse-papier pour que
        // l'utilisateur puisse coller lui-même.
        if IsSecureEventInputEnabled() {
            write(text, transient: false)
            throw .secureInputActive
        }
        // Sans Accessibilité, les événements clavier simulés sont ignorés.
        guard AXIsProcessTrusted() else {
            write(text, transient: false)
            throw .accessibilityNotGranted
        }

        let saved = restoreClipboard ? snapshot() : nil
        write(text, transient: true)
        let ourChangeCount = pasteboard.changeCount

        try postCommandV()

        guard let saved else { return }
        try? await Task.sleep(for: restoreDelay)
        // Si le presse-papier a changé depuis (l'utilisateur a copié autre
        // chose), on ne touche à rien : on écraserait sa copie.
        if pasteboard.changeCount == ourChangeCount {
            restore(saved)
        } else {
            logger.debug("Presse-papier modifié entre-temps, pas de restauration")
        }
    }

    // MARK: - Presse-papier

    /// Contenu complet du presse-papier : chaque élément, chaque type, en données brutes.
    private typealias Snapshot = [[NSPasteboard.PasteboardType: Data]]

    private func snapshot() -> Snapshot {
        (pasteboard.pasteboardItems ?? []).map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { entry[type] = data }
            }
            return entry
        }
    }

    private func restore(_ saved: Snapshot) {
        pasteboard.clearContents()
        guard !saved.isEmpty else { return }
        let items = saved.map { entry in
            let item = NSPasteboardItem()
            for (type, data) in entry { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
    }

    /// Écrit le texte. `transient` ajoute des types « marqueurs » reconnus par
    /// les gestionnaires de presse-papier (Maccy, Raycast, Alfred…) : ils
    /// n'enregistrent pas ce contenu dans leur historique.
    /// Convention : http://nspasteboard.org
    private func write(_ text: String, transient: Bool) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        if transient {
            pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
            pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        }
    }

    // MARK: - ⌘V simulé

    private func postCommandV() throws(InsertionError) {
        let vKey = KeyboardLayout.keyCode(for: "v")
        // `.combinedSessionState` : l'événement hérite de l'état clavier de la
        // session, mais on force explicitement les drapeaux à « ⌘ seul » pour
        // ignorer ⌃/⌥ éventuellement encore enfoncés par l'utilisateur.
        let source = CGEventSource(stateID: .combinedSessionState)
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        else { throw .eventCreationFailed }

        for event in [down, up] {
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData, value: SyntheticEvents.marker)
            // Envoi au niveau « matériel » (HID) : l'événement passe par tout le
            // circuit normal, comme une vraie frappe, jusqu'à l'app au premier plan.
            event.post(tap: .cghidEventTap)
        }
    }
}
